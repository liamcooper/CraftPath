#!/usr/bin/env python3
"""Builds DisenchantData.lua from Auctionator's classic disenchant table (which Forever does not load).
Usage: make_disenchant.py <Auctionator/Source_Classic/Enchant/DisenchantingProbabilities.lua> <out>"""
import sys, re
lines = open(sys.argv[1], encoding="utf-8").read().replace("\r\n", "\n").split("\n")
start = next(i for i, l in enumerate(lines) if l.startswith("Auctionator.Constants.DisenchantingProbability = {"))
end = next(i for i in range(start + 1, len(lines)) if lines[i] == "}")
body = [l for l in lines[start + 1:end] if l.strip() and not l.strip().startswith("--")]
text = "\n".join(body)
for a, b in [("[ Enum.ItemClass.Armor ]", "[4]"), ("[ Enum.ItemClass.Weapon ]", "[2]"),
             ("[ Enum.ItemQuality.Good ]", "[2]"), ("[ Enum.ItemQuality.Rare ]", "[3]"), ("[ Enum.ItemQuality.Epic ]", "[4]")]:
    assert a in text, a
    text = text.replace(a, b)
assert "Enum" not in text and "Auctionator" not in text
out = """-- CraftPath :: DisenchantData
-- GENERATED by tools/make_disenchant.py from Auctionator's classic disenchant table (personal use).
-- [item class][quality] = { { lowItemLevel, highItemLevel, chance%, quantity, materialItemID, chance%, quantity, materialItemID, ... }, ... }
-- Item class 4 = armour, 2 = weapon. Quality 2 = green, 3 = blue, 4 = purple.
local _, CPath = ...
CPath.DisenchantTable = {
""" + text + """
}
-- Three lesser essences combine into one greater, so a lesser is worth at least a third of the greater.
CPath.EssenceUpgrade = { [10938] = 10939, [10998] = 11082, [11134] = 11135, [11174] = 11175, [16202] = 16203 }
"""
open(sys.argv[2], "w", encoding="utf-8").write(out)
print("wrote", sys.argv[2])
